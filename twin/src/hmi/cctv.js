// S09 CCTV: camera list by area, live tiles rendered procedurally (or through the platform renderer hook
// ctx.renderCameraView(cameraComponentId, canvas, view) when available), PTZ control with presets,
// recorder status, health alarms, alarm call-up, analogue (legacy) versus IP (retrofit) pictures.
import { createFrame, h, btn, kv, text, f0, miniFrame } from './common/ui.js'
import { PTZ_PRESETS } from '../sim/telecom.js'

export const meta = { id: 'cctv', title: 'CCTV', systems: ['S09'], kind: 'hmi' }

export function mount(container, ctx) {
  const fr = createFrame(container, ctx, {
    moduleId: 'cctv', systemId: 'S09', title: 'CCTV: closed circuit television',
    help: 'Cameras watch machinery spaces, process decks, the turret and the offloading station. The CCTV desk shows live pictures, moves the pan, tilt and zoom cameras, records everything on the network video recorder and brings the nearest camera to the screen automatically when the fire and gas system raises an alarm.',
    alarmSystems: ['S09'],
    status: (st, api) => [st.cctv.status, st.cctv.status === 'Live view' ? '' : 'high'],
    tabs: [
      { id: 'desk', label: 'CCTV desk', build: (el, api) => buildDesk(el, ctx, api) },
      { id: 'cams', label: 'Cameras and recorder', build: (el) => buildCams(el, ctx) },
    ],
  })
  return { unmount: () => fr.destroy(), setVariant: (v) => fr.setVariant(v), frame: fr }
}

function buildDesk(el, ctx, api) {
  const { sim } = ctx
  const legacy = api.variant === 'legacy'
  const st0 = sim.state
  const cams = st0.cctv.cameras
  const main = h('canvas', { style: { width: '100%', height: '19em', background: '#000' }, 'aria-label': 'Selected camera', 'data-view': 'main' })
  const tiles = cams.slice(0, 8).map((c) => { const cv = h('canvas', { style: { width: '100%', height: '6em', background: '#000', cursor: 'pointer' }, 'aria-label': c.tag, onclick: () => sim.command('cctv.select', { cam: c.id }) }); return [c.id, cv] })
  const title = h('h3', {}, '')
  const ptz = h('div', { class: 'grid', style: { gridTemplateColumns: 'repeat(3, 4.6em)', gap: '.3em' } },
    h('span'), btn('Up', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dt: 5 }), '', { 'data-act': 'ptz-up' }), h('span'),
    btn('Left', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dp: -10 }), '', { 'data-act': 'ptz-left' }), h('span'), btn('Right', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dp: 10 }), '', { 'data-act': 'ptz-right' }),
    h('span'), btn('Down', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dt: -5 })), h('span'))
  const zoom = h('div', { class: 'row' }, btn('Zoom in', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dz: 1 })), btn('Zoom out', () => sim.command('cctv.ptz', { cam: sim.state.cctv.selected, dz: -1 })))
  const presets = h('div', { class: 'row' }, ...PTZ_PRESETS.map((p) => btn(p.name, () => sim.command('cctv.preset', { cam: sim.state.cctv.selected, n: p.n }), '', { 'data-preset': p.n })))
  const K = kv([['Pan', 'deg', 'p'], ['Tilt', 'deg', 't'], ['Zoom', 'x', 'z'], ['Recording', '', 'r']])
  const callup = h('div', { class: 'note' }, '')
  el.append(h('div', { class: 'grid', style: { gridTemplateColumns: 'minmax(0,2.2fr) minmax(15em,1fr)' } },
    h('div', { class: 'card' }, title, main, h('div', { class: 'grid g4', style: { marginTop: '.4em' } }, ...tiles.map(([id, cv]) => h('div', {}, cv, h('div', { class: 'small' }, cams.find((c) => c.id === id).tag))))),
    h('div', { class: 'card' }, h('h3', {}, 'PTZ control'), ptz, zoom, h('h4', {}, 'Presets (PTZ cameras)'), presets, K.el, callup,
      legacy ? h('p', { class: 'note' }, 'Legacy view: analogue cameras on coaxial cable through a matrix switcher: low resolution, monochrome or poor colour, interference, limited recording.') : h('p', { class: 'small muted' }, 'Pictures are generated by the simulation for demonstration (no video files).'))))
  return (st) => {
    const X = st.cctv
    const sel = X.cameras.find((c) => c.id === X.selected) || X.cameras[0]
    text(title, `${sel.tag}  ${sel.name}  (${sel.area})${sel.ptz ? '  PTZ' : ''}`)
    drawCam(ctx, main, sel, st, legacy, true)
    for (const [id, cv] of tiles) drawCam(ctx, cv, X.cameras.find((c) => c.id === id), st, legacy, false)
    K.set('p', sel.ptz ? f0(sel.pan) : 'fixed'); K.set('t', sel.ptz ? f0(sel.tilt) : '-'); K.set('z', sel.ptz ? sel.zoom.toFixed(1) : '-'); K.set('r', sel.recording ? 'recording' : 'NOT recording', sel.recording ? '' : 'high')
    text(callup, X.callup && st.t - X.callup.t < 60 ? `Alarm call-up: ${X.callup.reason}` : 'No alarm call-up'); callup.className = X.callup && st.t - X.callup.t < 60 ? 'note high' : 'note'
  }
}

function sceneKind(c) { const r = c.room || ''; return /PROC|TURRET|IG_DECK|OFFLOAD/.test(r) ? 'deck' : /PUMP/.test(r) ? 'pump' : 'machinery' }

function drawCam(ctx, canvas, cam, st, legacy, big) {
  const w = canvas.clientWidth || 320, hh = canvas.clientHeight || 180
  const scale = big ? 1 : 0.5
  if (canvas.width !== Math.round(w * scale)) { canvas.width = Math.round(w * scale); canvas.height = Math.round(hh * scale) }
  const W = canvas.width, H = canvas.height
  if (typeof ctx.renderCameraView === 'function' && big) { try { if (ctx.renderCameraView(cam.id, canvas, { pan: cam.pan, tilt: cam.tilt, zoom: cam.zoom }) !== false) { overlay(canvas, cam, st, legacy); return } } catch (e) { /* fall back */ } }
  const g = canvas.getContext('2d')
  if (cam.status !== 'ok') {
    g.fillStyle = cam.status === 'tamper' ? '#2a2a2a' : '#000'; g.fillRect(0, 0, W, H)
    g.fillStyle = '#ffb300'; g.font = `bold ${Math.round(H / 8)}px Segoe UI, Arial`; g.fillText(cam.status === 'tamper' ? 'TAMPER' : 'VIDEO LOSS', W * 0.08, H / 2)
    overlay(canvas, cam, st, legacy); return
  }
  const k = sceneKind(cam)
  const pan = ((cam.pan || 0) / 180) * W * 0.5, z = 1 + ((cam.zoom || 1) - 1) * 0.15, tilt = (cam.tilt || 0) * (H / 160)
  g.save()
  g.fillStyle = k === 'deck' ? '#7f97ad' : '#3b4046'; g.fillRect(0, 0, W, H)
  if (k === 'deck') {
    const sky = g.createLinearGradient(0, 0, 0, H * 0.5); sky.addColorStop(0, '#9fb7cc'); sky.addColorStop(1, '#d6dee5'); g.fillStyle = sky; g.fillRect(0, 0, W, H * 0.5 + tilt)
    g.fillStyle = '#4c5a66'; g.fillRect(0, H * 0.5 + tilt, W, H)
  }
  g.translate(W / 2 - pan, H * 0.55 + tilt); g.scale(z, z)
  const base = cam.seed * 37
  for (let i = -4; i <= 4; i++) {
    const x = i * W * 0.22
    if (k === 'deck') { g.fillStyle = '#5d6872'; g.fillRect(x - 40, -H * 0.35, 70, H * 0.35); g.fillStyle = '#c9a227'; g.fillRect(x - 46, -H * 0.36, 82, 6); g.strokeStyle = '#2e3a44'; g.lineWidth = 3; g.beginPath(); g.moveTo(x - 60, -H * 0.05); g.lineTo(x + 60, -H * 0.05); g.stroke() }
    else if (k === 'pump') { g.fillStyle = '#6a737c'; g.beginPath(); g.arc(x, -H * 0.1, 26, 0, Math.PI * 2); g.fill(); g.fillStyle = '#9aa3ab'; g.fillRect(x - 6, -H * 0.4, 12, H * 0.3) }
    else { g.fillStyle = '#6b6f63'; g.fillRect(x - 60, -H * 0.22, 110, H * 0.2); g.fillStyle = '#8b2f2f'; g.fillRect(x + 34, -H * 0.24, 20, H * 0.22); g.fillStyle = '#2d2f33'; g.fillRect(x - 70, -H * 0.02, 130, 8) }
  }
  const px = Math.sin(st.t * 0.3 + base) * W * 0.3
  g.fillStyle = '#ff7a00'; g.fillRect(px - 5, -H * 0.12, 10, 22); g.beginPath(); g.arc(px, -H * 0.14, 6, 0, Math.PI * 2); g.fill() // crew member in coverall
  g.restore()
  if (k === 'deck' && cam.ptz && Math.abs(cam.pan - 120) < 25 && cam.tilt > 10) { // view towards the flare tips (PTZ preset)
    const fl = 1 + 0.15 * Math.sin(st.t * 7 + base), zz = Math.min(3, 0.6 + (cam.zoom || 1) * 0.35) * (H / 330)
    const cx = W / 2 - ((cam.pan - 120) / 25) * W * 0.4, top = H * 0.18
    g.fillStyle = '#6f757b'; g.fillRect(cx - 5 * zz, top + 30 * zz, 10 * zz, H)
    g.strokeStyle = '#6f757b'; g.lineWidth = 2; for (let i = 0; i < 6; i++) { g.beginPath(); g.moveTo(cx - 5 * zz, top + 30 * zz + i * 25 * zz); g.lineTo(cx + 5 * zz, top + 42 * zz + i * 25 * zz); g.stroke() }
    g.fillStyle = '#ff9f1a'; g.beginPath(); g.ellipse(cx, top + 10 * zz, 14 * zz * fl, 28 * zz * fl, 0, 0, Math.PI * 2); g.fill()
    g.fillStyle = '#ffe08a'; g.beginPath(); g.ellipse(cx, top + 14 * zz, 6 * zz * fl, 13 * zz * fl, 0, 0, Math.PI * 2); g.fill()
  }
  if (legacy) {
    const img = g.getImageData(0, 0, W, H); const d = img.data
    for (let i = 0; i < d.length; i += 4) { const y = 0.3 * d[i] + 0.59 * d[i + 1] + 0.11 * d[i + 2]; const n = (Math.random() - 0.5) * 50; d[i] = d[i + 1] = d[i + 2] = y + n }
    g.putImageData(img, 0, 0)
    if (big) { g.imageSmoothingEnabled = false; g.drawImage(canvas, 0, 0, W / 3, H / 3, 0, 0, W, H) }
  }
  overlay(canvas, cam, st, legacy)
}

function overlay(canvas, cam, st, legacy) {
  const g = canvas.getContext('2d')
  const W = canvas.width, H = canvas.height
  const scale = (canvas.clientWidth || W) / W
  const fpx = Math.round(15 / scale)
  const big = W > 500
  g.fillStyle = 'rgba(0,0,0,0.55)'; g.fillRect(0, 0, W, fpx * 1.4)
  g.fillStyle = '#fff'; g.font = `${fpx}px Consolas, monospace`; g.textBaseline = 'top'
  g.fillText(big ? `${cam.tag}  ${st.clock || ''}  ${legacy ? 'ANALOGUE' : cam.recording ? 'REC' : 'NO REC'}` : `${legacy ? 'ANLG' : cam.recording ? 'REC' : 'NO REC'}`, 6, fpx * 0.2)
  g.textBaseline = 'alphabetic'
}

function buildCams(el, ctx) {
  const { sim } = ctx
  const body = h('tbody')
  const rows = sim.state.cctv.cameras.map((c) => { const td = h('td', {}), rec = h('td', {}); body.append(h('tr', {}, h('td', {}, c.tag), h('td', {}, c.name), h('td', { class: 'small' }, c.area), h('td', { class: 'small' }, `${c.ptz ? 'PTZ' : 'fixed'}${c.ex ? ', ' + c.ex : ''}`), td, rec, h('td', {}, btn('Video loss', () => sim.command('cctv.fault', { cam: c.id, kind: 'video loss' })), btn('Tamper', () => sim.command('cctv.fault', { cam: c.id, kind: 'tamper' })), btn('Restore', () => sim.command('cctv.fault', { cam: c.id, kind: 'ok' }))))); return [td, rec] })
  const N = kv([['Recording', '', 'rec'], ['Disk array', '', 'raid'], ['Storage used', '%', 'sto'], ['Retention', 'days', 'ret'], ['Recording load', 'Mbit/s', 'br'], ['Recorder sizing (db)', '', 'size']])
  el.append(h('div', { class: 'grid', style: { gridTemplateColumns: 'minmax(0,2fr) minmax(15em,1fr)' } },
    h('div', { class: 'card', style: { overflow: 'auto' } }, h('table', { class: 't' }, h('thead', {}, h('tr', {}, h('th', {}, 'Camera'), h('th', {}, 'Name'), h('th', {}, 'Area'), h('th', {}, 'Type'), h('th', {}, 'Health'), h('th', {}, 'Rec'), h('th', {}, 'Test'))), body)),
    h('div', { class: 'card' }, h('h3', {}, 'Network video recorder'), N.el, h('div', { class: 'row' }, btn('Disk failure', () => sim.command('cctv.nvr', { raid: 'degraded' }), 'warn'), btn('Rebuild array', () => sim.command('cctv.nvr', { raid: 'healthy' })), btn('Stop recording', () => sim.command('cctv.nvr', { recording: false })), btn('Start recording', () => sim.command('cctv.nvr', { recording: true }))))))
  return (st) => {
    st.cctv.cameras.forEach((c, i) => { text(rows[i][0], c.status); rows[i][0].className = c.status === 'ok' ? '' : 'high'; text(rows[i][1], c.recording ? 'yes' : 'NO') })
    const n = st.cctv.nvr
    N.set('rec', n.recording ? 'on' : 'STOPPED', n.recording ? '' : 'crit'); N.set('raid', n.raid, n.raid === 'healthy' ? '' : 'high'); N.set('sto', f0(n.storage_pct)); N.set('ret', n.retention_days); N.set('br', f0(n.bitrate_mbps)); N.set('size', `${n.storage_tb ?? '-'} TB, RAID ${n.raid_level ?? '-'}, ${n.fps ?? '-'} fps`)
  }
}

export function renderMini(canvas, ctx) {
  const st = ctx.sim.state
  const X = st.cctv
  miniFrame(canvas, 'CCTV', [{ k: 'Status', v: X.status, alarm: X.status !== 'Live view' ? 'high' : null }, { k: 'Cameras ok', v: `${X.cameras.filter((c) => c.status === 'ok').length} / ${X.cameras.length}` }, { k: 'Recorder', v: X.nvr.recording ? X.nvr.raid : 'STOPPED' }, { k: 'Selected', v: (X.cameras.find((c) => c.id === X.selected) || {}).tag || '-' }])
}
